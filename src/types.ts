// Shared domain types — the contract between modules. See docs/ARCHITECTURE.md.
//
// Conventions (apply everywhere):
//   • Coordinates are [lon, lat] (LngLat), matching GeoJSON / maplibre.
//   • Distances in meters, durations in seconds.
//   • Timestamps are epoch MILLISECONDS and their names end in `Ms` (GBFS seconds are converted at the boundary).
//   • Text from feeds/routers/geocoders is untrusted: render it only as React text or a maplibre text-field.

export type LngLat = [lon: number, lat: number]
export type BBox = [west: number, south: number, east: number, north: number]
export type Units = 'imperial' | 'metric'
export type MapMode = 'bikes' | 'docks'
export type TravelMode = 'walk' | 'bike'

// ─── Systems ─────────────────────────────────────────────────────────────────────────────────────

/** Entry of the committed registry (src/data/systems.json, generated by scripts/update-systems.mjs). */
export interface BcycleSystem {
  id: string
  name: string
  city: string
  url: string
  timezone: string
  bbox: BBox
  /** Station medoid (a real station location), not the bbox midpoint. */
  center: LngLat
  stationCount: number
  /** false when the feed currently lists 0 stations (e.g. seasonal systems in winter). */
  active: boolean
  gbfsUrl: string
}

export interface AppLink {
  /** Custom scheme from system_information.rental_apps (e.g. "bcycle://"). */
  discoveryUri: string
  storeUri: string
}

export interface PassOption {
  id: string
  name: string
  price: number
  currency: string
  description: string
  /** Minutes included per ride, parsed from the plan text; null = pay per minute / unknown. */
  includedMinutes: number | null
  /** https URL or null (feed URLs often lack a scheme; normalized). */
  url: string | null
}

/** GET /api/system — slow-changing system details (system_information + system_pricing_plans). */
export interface SystemDetails {
  systemId: string
  name: string
  timezone: string
  phone: string | null
  email: string | null
  websiteUrl: string | null
  rentalApps: { ios: AppLink | null; android: AppLink | null }
  passes: PassOption[]
  /** Smallest includedMinutes among passes ("Not sure" default), or null. */
  defaultIncludedMinutes: number | null
}

// ─── Stations ────────────────────────────────────────────────────────────────────────────────────

export interface StationInfo {
  id: string
  /** Trimmed. */
  name: string
  address: string | null
  coord: LngLat
  /** _bcycle_station_type === 'Kiosk and Station'. Kiosk-less stations can only be rented via the app. */
  hasKiosk: boolean
  // No region_id or rental_uris: nothing uses them (the rental links redirect to a marketing page; the app
  // hand-off uses system_information.rental_apps), and they were half of every /api/stations response.
}

export interface StationStatus {
  bikes: number
  docks: number
  /** From num_bikes_available_types; null when the feed omits the breakdown. */
  ebikes: number | null
  classic: number | null
  isInstalled: boolean
  isRenting: boolean
  isReturning: boolean
}

/** Station info merged with its latest status (null if the station is missing from station_status). */
export interface Station extends StationInfo {
  status: StationStatus | null
}

export interface StationsSnapshot {
  systemId: string
  stations: readonly Station[]
  byId: ReadonlyMap<string, Station>
  /** station_status last_updated (feed time), epoch ms. */
  lastUpdatedMs: number
  /** When this snapshot was assembled, epoch ms. */
  fetchedAtMs: number
}

/** Client-side snapshot with change tracking (see src/data/hooks.ts). */
export interface ClientStationsSnapshot extends StationsSnapshot {
  /** Increments only when some station's counts or flags changed. Key effects on this. */
  revision: number
  changedIds: ReadonlySet<string>
}

/** Shared classification for map colors, StationCard, planner "low" logic (src/lib/stationState.ts). */
export type AvailabilityState = 'ok' | 'low' | 'none' | 'unavailable'

// ─── Routing ─────────────────────────────────────────────────────────────────────────────────────

export type ManeuverKind =
  | 'depart'
  | 'arrive'
  | 'straight'
  | 'slight-left'
  | 'slight-right'
  | 'left'
  | 'right'
  | 'sharp-left'
  | 'sharp-right'
  | 'uturn'
  | 'keep-left'
  | 'keep-right'
  | 'roundabout'
  | 'merge'
  | 'ramp'
  | 'ferry'
  | 'steps'
  | 'other'

export interface Maneuver {
  kind: ManeuverKind
  /** Display text, e.g. "Turn left onto Langdon Street." */
  instruction: string
  /** Spoken well before the maneuver — has NO distance; voice prepends "In {distance}, …". */
  verbalAlert?: string
  /** Spoken just before the maneuver (may already include a "Then …" multi-cue). */
  verbalPre?: string
  /** Spoken right after the previous maneuver ("Continue for 300 feet") — unit-dependent text. */
  verbalPost?: string
  /** Short form ("Bear left."), for last-second cues. */
  verbalSuccinct?: string
  /** verbalPre already announces the following maneuver too. */
  verbalMultiCue?: boolean
  streetNames?: string[]
  /** Roundabout exit number. */
  exitNumber?: number
  /** Side of the street for arrival maneuvers. */
  side?: 'left' | 'right'
  /** Meters from this maneuver to the next one (the length of this step). */
  distance: number
  /** Seconds for this step. */
  duration: number
  /** Where the maneuver happens (= leg.geometry[beginIndex]). */
  location: LngLat
  /** Step i covers geometry segments k with beginIndex <= k < endIndex (half-open). */
  beginIndex: number
  endIndex: number
  bearingAfter?: number
}

/** What a leg is for. Consumers find legs by role, never by index (short walk legs are omitted). */
export type LegRole = 'toPickup' | 'ride' | 'toDestination' | 'walkOnly'

export type Provider = 'valhalla' | 'osrm' | 'straight'

/**
 * Invariants every normalizer guarantees (and tests assert):
 *   • geometry.length >= 2 with no consecutive duplicate points;
 *   • maneuvers[0].beginIndex === 0; maneuvers[i].endIndex === maneuvers[i + 1].beginIndex;
 *   • the last maneuver has kind 'arrive' and beginIndex === endIndex === geometry.length - 1;
 *   • geometry[0] === from and geometry[last] === to: when the router snapped an endpoint more than 3 m away,
 *     the requested point is prepended/appended as a connector (indices shifted accordingly);
 *   • snapFromM / snapToM record how far the router snapped the requested points (can exceed 1 km).
 */
export interface RouteLeg {
  role: LegRole
  mode: TravelMode
  /** Requested start (station coordinate or user point). */
  from: LngLat
  /** Requested end. */
  to: LngLat
  geometry: LngLat[]
  snapFromM: number
  snapToM: number
  distance: number
  duration: number
  maneuvers: Maneuver[]
  provider: Provider
  /** Units/language the verbal text was generated in. */
  units: Units
  language: string
  /** toPickup → pickup station; ride → dropoff station. */
  stationId?: string
  /** Bike legs: Valhalla use_roads the route was computed with (0 = avoid car roads, 1 = road-happy). */
  useRoads?: number
}

